#!/usr/bin/env node
/* Builds the learning map's data from the pages and the curated graph.

     node tools/build-learning-map.js           write assets/js/learning-map-data.js
     node tools/build-learning-map.js --check   exit 1 if it is out of date or the
                                                graph doesn't cover every concept

   Two sources, deliberately split:
     - the PAGES are the truth for what a concept is: its id (page#anchor),
       title, difficulty, cross-links ("Connects to") and references;
     - data/learning-graph.json is the curated learning order: stages, each
       concept's stage, level, summary, why, prerequisites and practice
       exercise, and the role paths.

   A concept added to a page but not to the graph fails --check, so the map
   can't silently fall behind the guide. */

'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const GRAPH = path.join(ROOT, 'data', 'learning-graph.json');
const OUT = path.join(ROOT, 'assets', 'js', 'learning-map-data.js');

// Content pages, in guide order. A page without concept sections is skipped.
const PAGES = [
  ['01-distributed-systems.html', '01 · Distributed systems'],
  ['02-data-storage.html', '02 · Data & storage'],
  ['03-apis-contracts.html', '03 · APIs & contracts'],
  ['04-microservices-patterns.html', '04 · Microservices patterns'],
  ['05-reliability-observability.html', '05 · Reliability & observability'],
  ['06-performance-scale.html', '06 · Performance & scale'],
  ['07-security.html', '07 · Security'],
  ['08-data-platforms.html', '08 · Data platform architecture'],
  ['payment-system.html', 'Applied A · Payment processing'],
  ['order-fulfilment.html', 'Applied B · Order fulfilment'],
  ['lakehouse-platform.html', 'Applied C · Lakehouse platform'],
];

const text = s => s.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();

function readConcepts() {
  const out = [];
  for (const [file, pageTitle] of PAGES) {
    const h = fs.readFileSync(path.join(ROOT, file), 'utf8');
    for (const sec of h.split('<section class="pattern" id="').slice(1)) {
      const anchor = sec.slice(0, sec.indexOf('"'));
      const connects = [...((sec.match(/<div class="connects">([\s\S]*?)<\/div>/) || [])[1] || '').matchAll(/href="([^"]*)"/g)]
        .map(m => (m[1].startsWith('#') ? file + m[1] : m[1]))
        .filter(id => id.includes('#'));
      out.push({
        id: `${file}#${anchor}`,
        page: file,
        pageTitle,
        title: text((sec.match(/<h2[^>]*>([\s\S]*?)<\/h2>/) || [])[1] || ''),
        difficulty: (sec.match(/<span class="bar on">/g) || []).length,
        connects: [...new Set(connects)],
        references: [...sec.matchAll(/<div class="reference">([\s\S]*?)<\/div>/g)]
          .flatMap(m => [...m[1].matchAll(/<a href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g)].map(a => ({ url: a[1], title: text(a[2]) }))),
      });
    }
  }
  return out;
}

function build() {
  const concepts = readConcepts();
  const graph = JSON.parse(fs.readFileSync(GRAPH, 'utf8'));
  const ids = new Set(concepts.map(c => c.id));
  const problems = [];

  for (const c of concepts) if (!graph.concepts[c.id]) problems.push(`not in data/learning-graph.json: ${c.id} (${c.title})`);
  for (const id of Object.keys(graph.concepts)) if (!ids.has(id)) problems.push(`in the graph but not on any page: ${id}`);
  for (const [id, g] of Object.entries(graph.concepts))
    for (const p of g.prereqs || []) if (!ids.has(p)) problems.push(`${id}: prerequisite ${p} is not a concept`);

  const merged = concepts.filter(c => graph.concepts[c.id]).map(c => {
    const g = graph.concepts[c.id];
    return { ...c, connects: c.connects.filter(x => ids.has(x)), stage: g.stage, level: g.level, summary: g.summary, why: g.why, prereqs: g.prereqs || [], practice: g.practice };
  });
  const data = { stages: graph.stages, paths: graph.paths, concepts: merged };
  const js = '/* Generated by tools/build-learning-map.js from the pages and data/learning-graph.json.\n' +
             '   Do not edit by hand: change the graph or the pages and rebuild. */\n' +
             'window.LEARNING_MAP = ' + JSON.stringify(data) + ';\n';
  return { js, problems, count: merged.length };
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const { js, problems, count } = build();
  problems.forEach(p => console.log('  ' + p));
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== js) console.log('  learning map data out of date -- run node tools/build-learning-map.js');
    process.exit(problems.length || current !== js ? 1 : 0);
  }
  if (problems.length) process.exit(1);
  fs.writeFileSync(OUT, js);
  console.log(`learning map: ${count} concepts written to assets/js/learning-map-data.js`);
}
