/* ==========================================================================
   Learning map - learning-map.html
   Every concept in the guide, in the order that builds on itself.

   Data: window.LEARNING_MAP (assets/js/learning-map-data.js, generated by
   tools/build-learning-map.js from the pages + data/learning-graph.json).

   Two views of one selection:
     Mind map  stages branch into concepts; expand a stage to drill in.
     Path      a role's route through the guide, step by step.
   The panel shows the selected concept: what, why, what to know first, what
   it unlocks, a practice exercise, and the way into the page.

   Mastery (not started / read / practised / can explain) is saved in this
   browser under lm.m.<concept id>, the same keys the concept pages use, so
   marking a concept on its page shows up here and the other way round.
   ========================================================================== */

(function () {
  'use strict';

  var DATA = window.LEARNING_MAP;
  if (!DATA) return;

  /* ------------------------------------------------------------- state */

  var LEVELS = ['Not started', 'Read', 'Practised', 'Can explain'];
  var LEVEL_STATUS = ['neutral', 'neutral', 'info', 'success'];

  function store(key, val) {
    try {
      if (typeof val === 'undefined') return window.localStorage.getItem(key);
      if (val === null) window.localStorage.removeItem(key); else window.localStorage.setItem(key, String(val));
    } catch (e) { return null; }
    return null;
  }

  var byId = {}, stageIndex = {};
  DATA.stages.forEach(function (s, i) { stageIndex[s.id] = i; s.items = []; });
  DATA.concepts.forEach(function (c) { byId[c.id] = c; c.unlocks = []; });
  DATA.concepts.forEach(function (c) {
    c.prereqs.forEach(function (p) { if (byId[p]) byId[p].unlocks.push(c.id); });
    var s = DATA.stages[stageIndex[c.stage]]; if (s) s.items.push(c);
  });

  // Within a stage, order concepts so prerequisites come first.
  DATA.stages.forEach(function (s) {
    var seen = {}, out = [];
    var visit = function (c) {
      if (seen[c.id]) return; seen[c.id] = true;
      c.prereqs.forEach(function (p) { if (byId[p] && byId[p].stage === s.id) visit(byId[p]); });
      out.push(c);
    };
    s.items.forEach(visit);
    s.items = out;
  });

  var ALL_PATH = { id: 'all', title: 'Whole guide', summary: 'Every concept, stage by stage.', steps: [] };
  DATA.stages.forEach(function (s) { s.items.forEach(function (c) { ALL_PATH.steps.push(c.id); }); });
  var PATHS = DATA.paths.concat([ALL_PATH]);

  var mastery = function (id) { var v = parseInt(store('lm.m.' + id), 10); return isNaN(v) ? 0 : Math.max(0, Math.min(3, v)); };
  var setMastery = function (id, v) { store('lm.m.' + id, v > 0 ? v : null); };

  var view = store('lm.view') === 'path' ? 'path' : 'map';
  var pathId = store('lm.path') || 'engineer';
  if (!PATHS.some(function (p) { return p.id === pathId; })) pathId = PATHS[0].id;
  var query = '';
  var open = {};
  DATA.stages.forEach(function (s) { open[s.id] = store('lm.open.' + s.id) === '1'; });

  function currentPath() { return PATHS.filter(function (p) { return p.id === pathId; })[0]; }

  // Next up: on the current path, the first concept not yet read whose
  // prerequisites are all at least read; failing that, the first unread one.
  function nextUp() {
    var steps = currentPath().steps;
    var ready = steps.filter(function (id) {
      return byId[id] && mastery(id) === 0 && byId[id].prereqs.every(function (p) { return mastery(p) > 0; });
    });
    return ready[0] || steps.filter(function (id) { return byId[id] && mastery(id) === 0; })[0] || null;
  }

  var selected = null;
  (function initialSelection() {
    var m = /concept=([^&]+)/.exec(window.location.hash);
    var fromHash = m && decodeURIComponent(m[1]);
    selected = (fromHash && byId[fromHash]) ? fromHash : (store('lm.sel') && byId[store('lm.sel')] ? store('lm.sel') : nextUp() || ALL_PATH.steps[0]);
    open[byId[selected].stage] = true;
  }());

  /* ----------------------------------------------------------- helpers */

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }
  function svg(tag, attrs, text) {
    var e = document.createElementNS('http://www.w3.org/2000/svg', tag);
    for (var k in attrs) e.setAttribute(k, attrs[k]);
    if (text != null) e.textContent = text;
    return e;
  }
  function status(kind, text) { return el('span', 'hf-status hf-status--' + kind + ' hf-status--nodot', text); }
  function stageOf(c) { return DATA.stages[stageIndex[c.stage]]; }
  function href(c) { var i = c.id.indexOf('#'); return c.id.slice(0, i) + '#' + c.id.slice(i + 1); }
  function matches(c) {
    if (!query) return true;
    var q = query.toLowerCase();
    return (c.title + ' ' + c.summary + ' ' + c.pageTitle).toLowerCase().indexOf(q) >= 0;
  }
  function trunc(s, n) { return s.length > n ? s.slice(0, n - 1) + '…' : s; }

  function select(id, opts) {
    if (!byId[id]) return;
    selected = id;
    store('lm.sel', id);
    var st = byId[id].stage;
    if (!open[st]) { open[st] = true; store('lm.open.' + st, '1'); }
    if (window.history && history.replaceState) history.replaceState(null, '', '#concept=' + encodeURIComponent(id));
    render();
    if (opts && opts.scrollPanel) {
      var p = document.getElementById('lm-panel');
      if (p && p.getBoundingClientRect().top < 0) p.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  }

  /* ------------------------------------------------------------ toolbar */

  function renderToolbar() {
    var host = document.getElementById('lm-toolbar');
    host.textContent = '';

    var views = el('div', 'btn-group kt-lm-views');
    views.setAttribute('role', 'group');
    views.setAttribute('aria-label', 'View');
    [['map', 'Mind map', 'bi-diagram-2'], ['path', 'Path', 'bi-signpost-split']].forEach(function (v) {
      var b = el('button', 'btn btn-sm ' + (view === v[0] ? 'btn-primary' : 'btn-secondary'));
      b.type = 'button';
      b.setAttribute('aria-pressed', view === v[0] ? 'true' : 'false');
      b.appendChild(el('i', 'bi ' + v[2]));
      b.appendChild(document.createTextNode(v[1]));
      b.addEventListener('click', function () { view = v[0]; store('lm.view', view); render(); });
      views.appendChild(b);
    });
    host.appendChild(views);

    var paths = el('div', 'kt-lm-paths');
    paths.appendChild(el('span', 'hf-caps', 'Path'));
    PATHS.forEach(function (p) {
      var b = el('button', 'btn hf-btn-pill' + (p.id === pathId ? ' is-active' : ''), p.title);
      b.type = 'button';
      b.title = p.summary;
      b.setAttribute('aria-pressed', p.id === pathId ? 'true' : 'false');
      b.addEventListener('click', function () { pathId = p.id; store('lm.path', pathId); render(); });
      paths.appendChild(b);
    });
    host.appendChild(paths);

    var search = el('div', 'kt-lm-search');
    var icon = el('i', 'bi bi-search');
    var input = el('input', 'form-control form-control-sm');
    input.type = 'search';
    input.id = 'lm-search';
    input.placeholder = 'Find a concept';
    input.setAttribute('aria-label', 'Find a concept');
    input.value = query;
    input.addEventListener('input', function () {
      query = input.value.trim();
      if (query) DATA.stages.forEach(function (s) { if (s.items.some(matches)) open[s.id] = true; });
      renderMain(); renderFacts();
    });
    search.appendChild(icon);
    search.appendChild(input);
    host.appendChild(search);
  }

  /* ----------------------------------------------------------- mind map */

  // Concept rows are 34 high; a collapsed stage gets 56 so its two-line
  // title fits. Stage titles wrap at ~26 characters, concept titles truncate
  // (the full title is in the tooltip and the panel).
  var ROW = 34, STAGE_ROW = 56, NODE_H = 26, STAGE_H = 48;
  var COL = { root: 0, stage: 172, concept: 408 };
  var WIDTH = { root: 150, stage: 210, concept: 330 };
  var CANVAS_W = COL.concept + WIDTH.concept + 4;

  function wrap2(s, n) {
    if (s.length <= n) return [s];
    var cut = s.lastIndexOf(' ', n);
    if (cut < 8) cut = n;
    var rest = s.slice(cut).trim();
    return [s.slice(0, cut), trunc(rest, n)];
  }

  function renderMap(host) {
    var sel = byId[selected];
    var related = {};
    sel.prereqs.forEach(function (p) { related[p] = 'prereq'; });
    sel.unlocks.forEach(function (u) { related[u] = 'unlock'; });
    var onPath = {};
    currentPath().steps.forEach(function (id, i) { onPath[id] = i + 1; });

    // Layout top to bottom: an open stage stacks its (matching) concepts and
    // sits at their vertical middle; a closed stage takes one taller row.
    // Every node stores its centre y in px.
    var y = 8, layout = [], cy = {};
    DATA.stages.forEach(function (s) {
      var items = s.items.filter(matches);
      if (query && !items.length) return;
      var top = y;
      if (open[s.id] && items.length) {
        items.forEach(function (c) { cy[c.id] = y + ROW / 2; layout.push({ c: c, cy: cy[c.id] }); y += ROW; });
        y += 8;                                   // breathing room between open stages
      } else {
        y += STAGE_ROW;
      }
      layout.push({ s: s, items: items, cy: Math.max(top + STAGE_H / 2, (top + y) / 2 - (open[s.id] && items.length ? 4 : 0)) });
    });
    var H = Math.max(y, 60) + 8;
    var stageNodes = layout.filter(function (n) { return n.s; });
    var rootY = stageNodes.length ? (stageNodes[0].cy + stageNodes[stageNodes.length - 1].cy) / 2 : 30;
    var mid = function (v) { return v; };

    var map = svg('svg', { viewBox: '0 0 ' + CANVAS_W + ' ' + H, class: 'kt-lm-svg', role: 'tree', 'aria-label': 'Learning map' });
    var edges = svg('g', {}), nodes = svg('g', {});
    map.appendChild(edges); map.appendChild(nodes);

    var curve = function (x1, y1, x2, y2, cls) {
      var dx = (x2 - x1) / 2;
      edges.appendChild(svg('path', { d: 'M' + x1 + ' ' + y1 + ' C' + (x1 + dx) + ' ' + y1 + ' ' + (x2 - dx) + ' ' + y2 + ' ' + x2 + ' ' + y2,
        fill: 'none', stroke: cls === 'hot' ? 'var(--hf-ink)' : 'var(--hf-hairline)', 'stroke-width': cls === 'hot' ? 1.5 : 1 }));
    };

    // Root.
    var root = svg('g', {});
    root.appendChild(svg('rect', { x: COL.root, y: rootY - 18, width: WIDTH.root, height: 36, rx: 2, fill: 'var(--hf-ink)' }));
    root.appendChild(svg('text', { x: COL.root + 12, y: rootY - 2, fill: 'var(--hf-on-primary)', 'font-family': 'var(--hf-font)', 'font-size': 12, 'font-weight': 700 }, 'Backend and'));
    root.appendChild(svg('text', { x: COL.root + 12, y: rootY + 12, fill: 'var(--hf-on-primary)', 'font-family': 'var(--hf-font)', 'font-size': 12, 'font-weight': 700 }, 'solutions architecture'));
    nodes.appendChild(root);

    layout.forEach(function (n) {
      if (n.s) {
        var s = n.s, y = mid(n.cy), isSelStage = sel.stage === s.id;
        var done = s.items.filter(function (c) { return mastery(c.id) > 0; }).length;
        curve(COL.root + WIDTH.root, rootY, COL.stage, y, isSelStage ? 'hot' : '');
        var g = svg('g', { class: 'kt-lm-node kt-lm-stage', tabindex: 0, role: 'treeitem', 'aria-expanded': open[s.id] ? 'true' : 'false' });
        g.appendChild(svg('rect', { x: COL.stage, y: y - STAGE_H / 2, width: WIDTH.stage, height: STAGE_H, rx: 2,
          fill: 'var(--hf-surface)', stroke: isSelStage ? 'var(--hf-ink)' : 'var(--hf-hairline-strong)', 'stroke-width': isSelStage ? 1.5 : 1 }));
        var lines = wrap2(s.title, 26);
        g.appendChild(svg('text', { x: COL.stage + 10, y: y - (lines.length > 1 ? 9 : 2), fill: 'var(--hf-ink-muted)', 'font-family': 'var(--hf-font)', 'font-size': 12 },
          open[s.id] ? '▾' : '▸'));
        lines.forEach(function (line, li) {
          g.appendChild(svg('text', { x: COL.stage + 24, y: y - (lines.length > 1 ? 9 : 2) + li * 14, fill: 'var(--hf-ink)', 'font-family': 'var(--hf-font)', 'font-size': 12, 'font-weight': 600 }, line));
        });
        g.appendChild(svg('text', { x: COL.stage + 24, y: y + (lines.length > 1 ? 19 : 13), fill: 'var(--hf-ink-muted)', 'font-family': 'var(--hf-font-mono)', 'font-size': 10 },
          done + ' / ' + s.items.length + ' started'));
        g.appendChild(svg('title', {}, s.title + ': ' + s.summary));
        var toggle = function () { open[s.id] = !open[s.id]; store('lm.open.' + s.id, open[s.id] ? '1' : null); renderMain(); };
        g.addEventListener('click', toggle);
        g.addEventListener('keydown', function (e) { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); toggle(); } });
        nodes.appendChild(g);
        if (open[s.id]) n.items.forEach(function (c) {
          curve(COL.stage + WIDTH.stage, y, COL.concept, cy[c.id], c.id === selected ? 'hot' : '');
        });
      } else {
        var c = n.c, yy = mid(n.cy), m = mastery(c.id), isSel = c.id === selected, rel = related[c.id];
        var g2 = svg('g', { class: 'kt-lm-node kt-lm-concept' + (onPath[c.id] ? '' : ' is-off-path'), tabindex: 0, role: 'treeitem' });
        g2.appendChild(svg('rect', { x: COL.concept, y: yy - NODE_H / 2, width: WIDTH.concept, height: NODE_H, rx: 2,
          fill: isSel ? 'var(--hf-ink)' : 'var(--hf-surface)',
          stroke: isSel ? 'var(--hf-ink)' : rel === 'prereq' ? 'var(--hf-info-fg)' : rel === 'unlock' ? 'var(--hf-ink-secondary)' : 'var(--hf-hairline)',
          'stroke-width': rel || isSel ? 1.5 : 1, 'stroke-dasharray': rel === 'unlock' ? '4 3' : 'none' }));
        // Mastery dot: hollow → read (muted) → practised (info) → can explain (success).
        var dotFill = ['none', 'var(--hf-ink-muted)', 'var(--hf-info-fg)', 'var(--hf-success-fg)'][m];
        g2.appendChild(svg('circle', { cx: COL.concept + 12, cy: yy, r: 4.5, fill: isSel && m === 0 ? 'none' : dotFill,
          stroke: isSel ? 'var(--hf-on-primary)' : (m ? dotFill : 'var(--hf-hairline-strong)'), 'stroke-width': 1.5 }));
        g2.appendChild(svg('text', { x: COL.concept + 24, y: yy + 4, fill: isSel ? 'var(--hf-on-primary)' : 'var(--hf-ink)',
          'font-family': 'var(--hf-font)', 'font-size': 12, 'font-weight': isSel ? 600 : 400 }, trunc(c.title, 48)));
        g2.appendChild(svg('title', {}, c.title + ' (' + c.pageTitle + ') · ' + LEVELS[m]));
        g2.addEventListener('click', function () { select(c.id, { scrollPanel: true }); });
        g2.addEventListener('keydown', function (e) { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); select(c.id, { scrollPanel: true }); } });
        nodes.appendChild(g2);
      }
    });

    var scroll = el('div', 'kt-lm-mapscroll');
    scroll.appendChild(map);
    host.appendChild(scroll);

    var legend = el('div', 'kt-lm-legend');
    legend.appendChild(el('span', 'hf-meta', 'Selected concept: its prerequisites are outlined in blue, what it unlocks is dashed. Faded concepts are not on the ' + currentPath().title.toLowerCase() + ' path.'));
    host.appendChild(legend);
  }

  /* --------------------------------------------------------------- path */

  function renderPath(host) {
    var p = currentPath(), nu = nextUp();
    var intro = el('p', 'kt-lm-pathintro');
    intro.appendChild(el('strong', null, p.title + ' · ' + p.steps.length + ' concepts. '));
    intro.appendChild(document.createTextNode(p.summary));
    host.appendChild(intro);

    var lastStage = null, n = 0, list = null;
    p.steps.forEach(function (id) {
      var c = byId[id];
      if (!c) return;
      n++;
      if (!matches(c)) return;
      if (c.stage !== lastStage) {
        lastStage = c.stage;
        host.appendChild(el('p', 'hf-eyebrow kt-lm-pathstage', stageOf(c).title));
        list = el('ol', 'kt-lm-steps');
        host.appendChild(list);
      }
      var m = mastery(id);
      var li = el('li');
      var b = el('button', 'kt-lm-step' + (id === selected ? ' is-selected' : '') + (m ? ' is-m' + m : ''));
      b.type = 'button';
      b.appendChild(el('span', 'kt-lm-step__n', String(n)));
      var t = el('span', 'kt-lm-step__main');
      t.appendChild(el('span', 'kt-lm-step__title', c.title));
      t.appendChild(el('span', 'hf-meta', c.pageTitle));
      b.appendChild(t);
      var tags = el('span', 'kt-lm-step__tags');
      if (id === nu) tags.appendChild(status('solid', 'Next up'));
      if (m) tags.appendChild(status(LEVEL_STATUS[m], LEVELS[m]));
      b.appendChild(tags);
      b.addEventListener('click', function () { select(id, { scrollPanel: true }); });
      li.appendChild(b);
      list.appendChild(li);
    });
  }

  /* -------------------------------------------------------------- panel */

  function chipList(ids, emptyText) {
    var wrap = el('div', 'kt-lm-chips');
    if (!ids.length) { wrap.appendChild(el('span', 'hf-meta', emptyText)); return wrap; }
    ids.forEach(function (id) {
      var c = byId[id]; if (!c) return;
      var b = el('button', 'kt-lm-chip' + (mastery(id) ? ' is-known' : ''));
      b.type = 'button';
      if (mastery(id)) b.appendChild(el('i', 'bi bi-check2'));
      b.appendChild(document.createTextNode(c.title));
      b.title = c.pageTitle;
      b.addEventListener('click', function () { select(id, { scrollPanel: true }); });
      wrap.appendChild(b);
    });
    return wrap;
  }

  function renderPanel() {
    var host = document.getElementById('lm-panel');
    host.textContent = '';
    var c = byId[selected], m = mastery(c.id), p = currentPath();

    var head = el('div', 'card-header');
    head.appendChild(el('span', 'hf-caps', stageOf(c).title));
    head.appendChild(status(c.level === 'advanced' ? 'warning' : 'neutral', c.level));
    host.appendChild(head);

    var body = el('div', 'card-body kt-lm-panel__body');
    body.appendChild(el('p', 'hf-meta kt-lm-panel__page', c.pageTitle));
    body.appendChild(el('h2', 'kt-lm-panel__title', c.title));
    body.appendChild(el('p', 'kt-lm-panel__summary', c.summary));

    var why = el('div', 'kt-lm-panel__block');
    why.appendChild(el('h3', null, 'Why it matters'));
    why.appendChild(el('p', null, c.why));
    body.appendChild(why);

    var read = el('a', 'btn btn-primary kt-lm-read', 'Read it in the guide');
    read.href = href(c);
    read.appendChild(el('i', 'bi bi-arrow-right'));
    body.appendChild(read);

    // Mastery: one segmented control, saved per concept.
    var mwrap = el('div', 'kt-lm-panel__block');
    mwrap.appendChild(el('h3', null, 'Where you are with it'));
    var seg = el('div', 'btn-group kt-lm-mastery');
    seg.setAttribute('role', 'radiogroup');
    seg.setAttribute('aria-label', 'Mastery');
    LEVELS.forEach(function (label, i) {
      var b = el('button', 'btn btn-sm ' + (m === i ? 'btn-primary' : 'btn-secondary'), label);
      b.type = 'button';
      b.setAttribute('role', 'radio');
      b.setAttribute('aria-checked', m === i ? 'true' : 'false');
      b.addEventListener('click', function () { setMastery(c.id, i); render(); });
      seg.appendChild(b);
    });
    mwrap.appendChild(seg);
    body.appendChild(mwrap);

    var pre = el('div', 'kt-lm-panel__block');
    pre.appendChild(el('h3', null, 'Know first'));
    pre.appendChild(chipList(c.prereqs, 'Nothing: a good place to start.'));
    body.appendChild(pre);

    var un = el('div', 'kt-lm-panel__block');
    un.appendChild(el('h3', null, 'Unlocks'));
    un.appendChild(chipList(c.unlocks, 'Nothing builds directly on this one.'));
    body.appendChild(un);

    var rel = c.connects.filter(function (id) { return c.prereqs.indexOf(id) < 0 && c.unlocks.indexOf(id) < 0; });
    if (rel.length) {
      var r = el('div', 'kt-lm-panel__block');
      r.appendChild(el('h3', null, 'Related'));
      r.appendChild(chipList(rel, ''));
      body.appendChild(r);
    }

    var pr = el('div', 'kt-lm-panel__block kt-lm-practice');
    pr.appendChild(el('h3', null, 'Practise it'));
    pr.appendChild(el('p', null, c.practice));
    body.appendChild(pr);

    if (c.references.length) {
      var refs = el('div', 'kt-lm-panel__block');
      refs.appendChild(el('h3', null, 'Reference material'));
      var ul = el('ul', 'kt-lm-refs');
      c.references.forEach(function (ref) {
        var li = el('li'), a = el('a', null, ref.title);
        a.href = ref.url; a.target = '_blank'; a.rel = 'noopener';
        li.appendChild(a); ul.appendChild(li);
      });
      refs.appendChild(ul);
      body.appendChild(refs);
    }
    host.appendChild(body);

    // Path navigation: previous / next on the chosen path.
    var i = p.steps.indexOf(c.id);
    var foot = el('div', 'card-footer kt-lm-panel__nav');
    var mk = function (id, label, icon, after) {
      var b = el('button', 'btn btn-secondary btn-sm');
      b.type = 'button';
      if (!after) b.appendChild(el('i', 'bi ' + icon));
      b.appendChild(document.createTextNode(label));
      if (after) b.appendChild(el('i', 'bi ' + icon));
      if (id) { b.title = byId[id].title; b.addEventListener('click', function () { select(id); }); } else b.disabled = true;
      return b;
    };
    foot.appendChild(mk(i > 0 ? p.steps[i - 1] : null, 'Previous', 'bi-arrow-left', false));
    foot.appendChild(el('span', 'hf-meta', i >= 0 ? 'Step ' + (i + 1) + ' of ' + p.steps.length + ' · ' + p.title : 'Not on the ' + p.title.toLowerCase() + ' path'));
    foot.appendChild(mk(i >= 0 && i < p.steps.length - 1 ? p.steps[i + 1] : null, 'Next', 'bi-arrow-right', true));
    host.appendChild(foot);
  }

  /* -------------------------------------------------------------- facts */

  function renderFacts() {
    var total = DATA.concepts.length;
    var counts = [0, 0, 0, 0];
    DATA.concepts.forEach(function (c) { counts[mastery(c.id)]++; });
    var set = function (id, v) { var e = document.getElementById(id); if (e) e.textContent = v; };
    set('lm-fact-total', total);
    set('lm-fact-started', (total - counts[0]) + ' / ' + total);
    set('lm-fact-explain', counts[3]);
    var nu = nextUp();
    var nextEl = document.getElementById('lm-fact-next');
    if (nextEl) {
      nextEl.textContent = '';
      if (nu) {
        var b = el('button', 'kt-lm-nextup', byId[nu].title);
        b.type = 'button';
        b.addEventListener('click', function () { select(nu, { scrollPanel: true }); });
        nextEl.appendChild(b);
      } else nextEl.textContent = 'Path complete';
    }
  }

  /* ------------------------------------------------------------- render */

  function renderMain() {
    var host = document.getElementById('lm-main');
    host.textContent = '';
    if (view === 'map') renderMap(host); else renderPath(host);
  }

  function render() {
    renderToolbar();
    renderMain();
    renderPanel();
    renderFacts();
  }

  render();
}());
